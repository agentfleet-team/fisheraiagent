#!/usr/bin/env node
// Generates REPORT-t1b.md from out/t1b/ (probe output), t1b-videos.json (observed spoken language) and t1b-notes.md (method and verdict text).
import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const rd = (p) => JSON.parse(readFileSync(join(here, p), 'utf8'));
const videos = rd('t1b-videos.json');
const hls = readdirSync(join(here, 'out/t1b')).sort();
const primary = (c) => (c ?? '').split('-')[0].toLowerCase();
const esc = (s) => String(s ?? '').replace(/\|/g, '\\|').replace(/\n/g, ' ');
const tr = (t) => (t ? `${t.index}:${t.languageCode}${t.kind === 'asr' ? '(asr)' : ''}` : 'none');

// Candidate rules, each maps a record to the track it picks (or null). Computed here from the recorded output.
const rules = {
  'all indices (set)': (r) => r.named,
  'first index': (r) => (r.named?.[0] ? [r.named[0]] : null),
  'defaultCaptionTrackIndex': (r) => {
    const d = r.audioTracks[r.defaultAudioTrackIndex ?? 0]?.defaultCaptionTrackIndex;
    return d == null ? null : [r.tracks[d]].filter(Boolean);
  },
};
// A pick is correct when it is exactly one track and that track's language is a spoken language.
const correct = (picked, spoken) => !!picked && picked.length === 1 && spoken.includes(primary(picked[0].languageCode));

let md = '# T1b report: does captionTrackIndices name the spoken-language track? (fisheraiagent#79)\n\n';
md += 'Tables are generated by `npm run t1b` in `spike/captions` (`node t1b.mjs && node t1b-report.mjs`; Node >=22, no dependencies, read-only calls to youtube.com, no key). Source data: `out/t1b/<hl>/<videoId>.json`; recorded player responses: `fixtures/t1b/<hl>/<videoId>.player.json`.\n\n';
md += readFileSync(join(here, 't1b-notes.md'), 'utf8').trim() + '\n\n';

md += '## 1. Per video and hl\n\n';
md += 'Spoken language is **observed** by the seat from the title, channel and caption text (not from audio). `named` lists the tracks that `audioTracks[defaultAudioTrackIndex].captionTrackIndices` points to.\n\n';
md += '| video | hl | tracks in player order | captionTrackIndices | named track(s) | defaultCaptionTrackIndex | spoken (observed) | named set is exactly the spoken track |\n|---|---|---|---|---|---|---|---|\n';
const stats = {};
for (const v of videos) for (const hl of hls) {
  const r = rd(`out/t1b/${hl}/${v.videoId}.json`);
  const dct = r.audioTracks[r.defaultAudioTrackIndex ?? 0]?.defaultCaptionTrackIndex ?? null;
  const ok = correct(r.named, v.spoken);
  md += `| ${v.videoId} | ${hl} | ${esc(r.tracks.map(tr).join(' '))} | ${esc(JSON.stringify(r.captionTrackIndices))} | ${esc((r.named ?? []).map(tr).join(' '))} | ${dct ?? '-'} | ${v.spoken.join('+')} | ${ok ? 'yes' : 'NO'} |\n`;
  for (const [name, f] of Object.entries(rules)) {
    const p = f(r);
    (stats[name] ??= {})[`${v.videoId}|${hl}`] = { ok: correct(p, v.spoken), pick: p ? p.map(tr).join(' ') : 'none' };
  }
}

md += '\n## 2. Observation basis for the spoken language\n\n| video | spoken (observed) | basis |\n|---|---|---|\n';
for (const v of videos) md += `| ${v.videoId} | ${v.spoken.join('+')} | ${esc(v.basis)} |\n`;

md += '\n## 3. Candidate rules scored over every video and hl\n\n| rule | correct | wrong | wrong cases (video@hl: pick) |\n|---|---|---|---|\n';
for (const [name, s] of Object.entries(stats)) {
  const bad = Object.entries(s).filter(([, x]) => !x.ok);
  md += `| ${name} | ${Object.keys(s).length - bad.length} | ${bad.length} | ${esc(bad.map(([k, x]) => `${k.replace('|', '@')}: ${x.pick}`).join('; '))} |\n`;
}

md += '\n## 4. Does the result depend on hl?\n\n| video | player track order, en | player track order, zh-TW | same order | same captionTrackIndices |\n|---|---|---|---|---|\n';
if (hls.length > 1) for (const v of videos) {
  const a = rd(`out/t1b/${hls[0]}/${v.videoId}.json`);
  const b = rd(`out/t1b/${hls[1]}/${v.videoId}.json`);
  const oa = a.tracks.map((t) => t.languageCode).join(' ');
  const ob = b.tracks.map((t) => t.languageCode).join(' ');
  md += `| ${v.videoId} | ${oa} | ${ob} | ${oa === ob ? 'yes' : 'NO'} | ${JSON.stringify(a.captionTrackIndices) === JSON.stringify(b.captionTrackIndices) ? 'yes' : 'NO'} |\n`;
}
writeFileSync(join(here, 'REPORT-t1b.md'), md);
console.log(`wrote REPORT-t1b.md (${videos.length} videos x ${hls.length} hl)`);
