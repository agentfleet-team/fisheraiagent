#!/usr/bin/env node
// P6: generate REPORT.md tables from out/. The method choice and risk text come from notes.md (written by the builder).
import { readdirSync, readFileSync, writeFileSync, existsSync, statSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { sha256 } from './lib.mjs';

const here = dirname(fileURLToPath(import.meta.url));
const OUT = join(here, 'out');
const rd = (p) => JSON.parse(readFileSync(p, 'utf8'));
const dirs = (p) => (existsSync(p) ? readdirSync(p).filter((n) => statSync(join(p, n)).isDirectory()).sort() : []);
const walk = (p) => readdirSync(p).sort().flatMap((n) => (statSync(join(p, n)).isDirectory() ? walk(join(p, n)) : [join(p, n)]));

const methods = dirs(OUT).filter((m) => m !== 'compare');
const videoIds = [...new Set(methods.flatMap((m) => dirs(join(OUT, m))))].sort();
const titleOf = {};
for (const m of methods) for (const v of dirs(join(OUT, m))) {
  const f = join(OUT, m, v, 'tracks.json');
  if (existsSync(f)) titleOf[v] = rd(f).title;
}
const esc = (s) => String(s ?? '').replace(/\|/g, '\\|').replace(/\n/g, ' ');
let md = '# T0 report: can a Node service read YouTube caption tracks? (fisheraiagent#66)\n\n';
md += 'Tables below are generated by `node report.mjs` from `out/`. Rerun everything with `npm run all` in this folder (Node >=22, no dependencies, read-only network calls to youtube.com).\n\n';

md += '## 1. Every method tried, per video\n\n';
md += '| method | video | result | tracks | median ms (3 runs, P1+P2) | failure text |\n|---|---|---|---|---|---|\n';
for (const m of methods) for (const v of dirs(join(OUT, m))) {
  const base = join(OUT, m, v);
  const t = rd(join(base, 'timing.json'));
  if (existsSync(join(base, 'error.json'))) {
    const e = rd(join(base, 'error.json'));
    md += `| ${m} | ${v} | FAIL | - | - | ${esc(e.message)} |\n`;
  } else {
    const s = rd(join(base, 'spoken.json'));
    const tr = rd(join(base, 'tracks.json'));
    md += `| ${m} | ${v} | ${s.kind} | ${tr.tracks.length} | ${t.medianTotalMs} | |\n`;
  }
}

const chosen = 'innertube-android';
md += `\n## 2. Chosen method \`${chosen}\`: tracks, cues, first 3 cues\n\n`;
for (const v of dirs(join(OUT, chosen))) {
  const base = join(OUT, chosen, v);
  const tr = rd(join(base, 'tracks.json'));
  const s = rd(join(base, 'spoken.json'));
  md += `### ${v} (${esc(titleOf[v])}, ${tr.durationSeconds}s): kind **${s.kind}**\n\n`;
  md += `- Tracks (${tr.tracks.length}): ${tr.tracks.map((t) => `${t.languageCode}/${t.kind}`).join(', ') || 'none'}\n`;
  md += `- Audio tracks: ${tr.audioTracks.length}, default index ${tr.defaultAudioTrackIndex}\n`;
  md += `- Rule used: ${s.rule}; spoken language: ${s.spokenLanguage ?? 'unknown'}\n`;
  const cf = join(base, 'cues.json');
  if (existsSync(cf)) {
    const c = rd(cf);
    for (const [label, x] of Object.entries(c)) {
      md += `- Fetched \`${label}\` (${x.languageCode}): ${x.cueCount} cues, ${x.bytes} bytes. First 3: ${x.first3.map((q) => `\`${q.start.toFixed(1)}s ${esc(q.text)}\``).join('; ')}\n`;
    }
  }
  md += '\n';
}

md += '## 3. ASR-original rule check (P3)\n\n| video | asr tracks | spoken | rule |\n|---|---|---|---|\n';
for (const v of dirs(join(OUT, chosen))) {
  const s = rd(join(OUT, chosen, v, 'spoken.json'));
  md += `| ${v} | ${s.asrTrackCount} | ${s.spokenLanguage ?? 'unknown'} | ${esc(s.rule)} |\n`;
}

md += '\n## 4. ASR vs manual text match (P4)\n\n';
const cdir = join(OUT, 'compare', chosen);
if (existsSync(cdir)) {
  const files = readdirSync(cdir).sort();
  md += `Method: ${rd(join(cdir, files[0])).method}.\n\n| video | language | asr cues | manual cues | asr words | manual words | bag F1 | set Jaccard |\n|---|---|---|---|---|---|---|---|\n`;
  for (const f of files) {
    const c = rd(join(cdir, f));
    md += `| ${c.videoId} | ${c.a.language} | ${c.a.cues} | ${c.b.cues} | ${c.wordsA} | ${c.wordsB} | ${c.bagF1} | ${c.setJaccard} |\n`;
  }
}

md += '\n## 5. Timing (P5), chosen method\n\n| video | P1 median ms | P2 median ms | total median ms | runs ok |\n|---|---|---|---|---|\n';
for (const v of dirs(join(OUT, chosen))) {
  const t = rd(join(OUT, chosen, v, 'timing.json'));
  md += `| ${v} | ${t.medianP1Ms} | ${t.medianP2Ms} | ${t.medianTotalMs} | ${t.okRuns}/${t.runs.length} |\n`;
}

const files = walk(OUT);
const outSha = sha256(files.map((f) => f.slice(OUT.length) + sha256(readFileSync(f))).join('\n'));
md += `\n## 6. Provenance\n\nout/ file count ${files.length}; sha256 of out/ listing+contents: \`${outSha}\`. Timings vary run to run, so a rerun changes this hash; compare kinds, cue counts and timings within 2x.\n`;

const notes = join(here, 'notes.md');
if (existsSync(notes)) md += '\n' + readFileSync(notes, 'utf8');
writeFileSync(join(here, 'REPORT.md'), md);
console.log('REPORT.md written');
