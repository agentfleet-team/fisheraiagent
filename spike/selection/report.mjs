#!/usr/bin/env node
// Generate REPORT.md tables from results/*.json (fisheraiagent#75).
// The "Findings for RFC-3" section and the workflow run URLs come from notes.md
// (written by the builder) and are appended verbatim, like spike/captions.
import { readdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const RES = join(here, 'results');
const esc = (s) => String(s ?? '').replace(/\|/g, '\\|').replace(/\n/g, ' ');
const daysBetween = (isoTs, yyyymmdd) => {
  if (!yyyymmdd) return null;
  const up = new Date(`${yyyymmdd.slice(0, 4)}-${yyyymmdd.slice(4, 6)}-${yyyymmdd.slice(6, 8)}T00:00:00Z`);
  return Math.floor((new Date(isoTs) - up) / 86400_000);
};
const MIN_S = 8 * 60, MAX_S = 90 * 60;

const files = existsSync(RES) ? readdirSync(RES).filter((f) => f.endsWith('.json')).sort() : [];
const runs = files.map((f) => ({ file: f, doc: JSON.parse(readFileSync(join(RES, f), 'utf8')) }));
// One query row may carry the round-2 list `searches` or the round-1 `search`.
const searchesOf = (q) => q.searches ?? (q.search ? [q.search] : []);

let md = '# Selection spike: keyless YouTube search supply, Mac and cloud (fisheraiagent#75)\n\n';
md += 'Tables below are generated by `node report.mjs` from `results/`. ';
md += 'Rerun the Mac numbers with `npm run mac` in this folder (two runs, 10 min apart; Node >=22 and `uv`, no dependencies, read-only network calls to youtube.com). ';
md += 'Rerun the cloud numbers by re-running the `spike-selection` workflow (Actions tab or `gh run rerun`).\n\n';
md += 'Search calls: two filtered searches per query, both upload-date sort + type video + an upload-date filter (the RFC-003 parameters): this week `sp=CAISBAgDEAE%3D` and this month `sp=CAISBAgEEAE%3D`. ';
md += 'Each runs `uv run --with yt-dlp yt-dlp "<youtube results url>" --flat-playlist --playlist-end 20 -J` plus one read of the same results page, from whose `ytInitialData` (videoRenderer / lockupViewModel) the relative age text and CC badge come. ';
md += 'Per-video call: `uv run --with yt-dlp yt-dlp -J --skip-download <watch url>` on the top 3 deduplicated candidates per query (week hits first). No video, audio or caption bytes are downloaded.\n\n';

md += '## 1. Per-query search calls\n\n';
md += '| place | run | topic | query | filter | status | wall s | page | results | fields present (of n) |\n|---|---|---|---|---|---|---|---|---|---|\n';
for (const { doc } of runs) {
  for (const q of doc.queries) {
    for (const s of searchesOf(q)) {
      const fp = s.status === 'ok'
        ? Object.entries(s.fields_present).map(([k, v]) => `${k}:${v}`).join(' ')
        : '-';
      const status = s.status === 'ok' ? 'ok' : `ERR: ${esc((s.error || '').split('\n').pop() || s.error)}`;
      const page = s.page ? `${s.page.status === 'ok' ? `ok:${s.page.entry_count}` : `ERR: ${esc((s.page.error || '').split('\n').pop())}`}` : '-';
      md += `| ${doc.place} | ${doc.run} | ${q.topic_id} | ${esc(q.query)} | ${s.filter ?? '-'} | ${status} | ${s.wall_s} | ${page} | ${s.result_count} | ${fp} |\n`;
    }
  }
}

md += '\n## 2. Per-video full-metadata calls (top 3 per query)\n\n';
md += '| place | run | topic | query | # | video | status | wall s | uploaded | days old | dur (min) | views | followers | zh track | en track |\n|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|\n';
for (const { doc } of runs) {
  for (const q of doc.queries) {
    for (const v of q.videos) {
      if (v.status !== 'ok') {
        md += `| ${doc.place} | ${doc.run} | ${q.topic_id} | ${esc(q.query)} | ${v.rank} | ${v.id} | ERR: ${esc((v.error || '').split('\n').pop() || v.error)} | ${v.wall_s} | - | - | - | - | - | - | - |\n`;
        continue;
      }
      const age = daysBetween(doc.started_at, v.upload_date);
      md += `| ${doc.place} | ${doc.run} | ${q.topic_id} | ${esc(q.query)} | ${v.rank} | ${v.id} | ok | ${v.wall_s} | ${v.upload_date ?? '-'} | ${age ?? '-'} | ${v.duration != null ? (v.duration / 60).toFixed(1) : '-'} | ${v.view_count ?? '-'} | ${v.channel_follower_count ?? '-'} | ${v.captions.has_zh ? 'yes' : 'no'} | ${v.captions.has_en ? 'yes' : 'no'} |\n`;
    }
  }
}

md += '\n## 3. Supply: unique videos per topic and place, duration 8-90 min, page fields only\n\n';
md += 'Each search carries its own upload-date filter, so the week column is the <=7-day supply and the month column the <=30-day supply. Duration comes from the flat/page entry (`lengthText`); entries missing a duration are excluded from the band count. Counts dedupe by video id across that place\'s runs and the topic\'s queries.\n\n';
md += '| topic | place | week: unique | week: in band | week: CC | month: unique | month: in band | month: CC |\n|---|---|---|---|---|---|---|---|\n';
const topicIds = [...new Set(runs.flatMap(({ doc }) => doc.queries.map((q) => q.topic_id)))];
const places = [...new Set(runs.map(({ doc }) => doc.place))].sort();
for (const topic of topicIds) {
  for (const place of places) {
    const cells = {};
    let any = false;
    for (const filter of ['week', 'month']) {
      const seen = new Map(); // id -> entry
      for (const { doc } of runs.filter((r) => r.doc.place === place)) {
        for (const q of doc.queries.filter((q) => q.topic_id === topic)) {
          for (const s of searchesOf(q).filter((s) => s.filter === filter)) {
            for (const e of s.entries) {
              if (e.id && !seen.has(e.id)) seen.set(e.id, e);
            }
          }
        }
      }
      const vals = [...seen.values()];
      const inBand = vals.filter((e) => e.duration != null && e.duration >= MIN_S && e.duration <= MAX_S);
      const cc = vals.filter((e) => e.cc_badge === true).length;
      cells[filter] = { unique: seen.size, inBand: inBand.length, cc };
      any = any || seen.size > 0;
    }
    if (!any) continue;
    md += `| ${topic} | ${place} | ${cells.week.unique} | ${cells.week.inBand} | ${cells.week.cc} | ${cells.month.unique} | ${cells.month.inBand} | ${cells.month.cc} |\n`;
  }
}

md += '\n## 4. Errors (exact text)\n\n';
const errs = [];
for (const { doc } of runs) {
  for (const q of doc.queries) {
    for (const s of searchesOf(q)) {
      if (s.status !== 'ok') errs.push({ where: `${doc.place}/${doc.run} search "${q.query}" (${s.filter ?? '-'})`, text: s.error });
      if (s.page && s.page.status !== 'ok') errs.push({ where: `${doc.place}/${doc.run} page "${q.query}" (${s.filter ?? '-'})`, text: s.page.error });
    }
    for (const v of q.videos) if (v.status !== 'ok') errs.push({ where: `${doc.place}/${doc.run} video ${v.id} ("${q.query}" #${v.rank})`, text: v.error });
  }
}
if (errs.length === 0) {
  md += 'None.\n';
} else {
  const groups = new Map(); // normalized text -> {text, wheres}
  for (const e of errs) {
    const k = (e.text || 'unknown').replace(/\[youtube\] [\w-]{11}:/g, '[youtube] <id>:');
    if (!groups.has(k)) groups.set(k, { text: e.text || 'unknown', wheres: [] });
    groups.get(k).wheres.push(e.where);
  }
  for (const { text, wheres } of groups.values()) {
    md += `- **${wheres.length} call(s)** — ${wheres.slice(0, 6).join('; ')}${wheres.length > 6 ? `; … (${wheres.length - 6} more, same text)` : ''}:\n  \`\`\`\n  ${text}\n  \`\`\`\n`;
  }
}

const notes = join(here, 'notes.md');
if (existsSync(notes)) md += '\n' + readFileSync(notes, 'utf8');
writeFileSync(join(here, 'REPORT.md'), md);
console.log(`REPORT.md written from ${files.length} result files: ${files.join(', ') || '(none)'}`);
