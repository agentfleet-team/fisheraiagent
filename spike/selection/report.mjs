#!/usr/bin/env node
// Generate REPORT.md tables from results/*.json (fisheraiagent#75).
// The "Findings for RFC-3" section and the workflow run URLs come from notes.md
// (written by the builder) and are appended verbatim, like spike/captions.
import { readdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const RES = join(here, 'results');
const esc = (s) => String(s ?? '').replace(/\|/g, '\\|').replace(/\n/g, ' ');
const daysBetween = (isoTs, yyyymmdd) => {
  if (!yyyymmdd) return null;
  const up = new Date(`${yyyymmdd.slice(0, 4)}-${yyyymmdd.slice(4, 6)}-${yyyymmdd.slice(6, 8)}T00:00:00Z`);
  return Math.floor((new Date(isoTs) - up) / 86400_000);
};
const MIN_S = 8 * 60, MAX_S = 90 * 60;

const files = existsSync(RES) ? readdirSync(RES).filter((f) => f.endsWith('.json')).sort() : [];
const runs = files.map((f) => ({ file: f, doc: JSON.parse(readFileSync(join(RES, f), 'utf8')) }));

let md = '# Selection spike: keyless YouTube search supply, Mac and cloud (fisheraiagent#75)\n\n';
md += 'Tables below are generated by `node report.mjs` from `results/`. ';
md += 'Rerun the Mac numbers with `npm run mac` in this folder (two runs, 10 min apart; Node >=22 and `uv`, no dependencies, read-only network calls to youtube.com). ';
md += 'Rerun the cloud numbers by re-running the `spike-selection` workflow (Actions tab or `gh run rerun`).\n\n';
md += 'Search call: `uv run --with yt-dlp yt-dlp "<youtube results url>&sp=EgIQAQ==" --flat-playlist --playlist-end 20 -J` (upload-date sort; the ticket\'s `ytsearchdate20:` prefix no longer exists in yt-dlp 2026.11.23). ';
md += 'Per-video call: `uv run --with yt-dlp yt-dlp -J --skip-download <watch url>` on the top 3 entries. No video, audio or caption bytes are downloaded.\n\n';

md += '## 1. Per-query search calls\n\n';
md += '| place | run | topic | query | status | wall s | results | fields present (of n) |\n|---|---|---|---|---|---|---|---|\n';
for (const { doc } of runs) {
  for (const q of doc.queries) {
    const s = q.search;
    const fp = s.status === 'ok'
      ? Object.entries(s.fields_present).map(([k, v]) => `${k}:${v}`).join(' ')
      : '-';
    const status = s.status === 'ok' ? 'ok' : `ERR: ${esc((s.error || '').split('\n').pop() || s.error)}`;
    md += `| ${doc.place} | ${doc.run} | ${q.topic_id} | ${esc(q.query)} | ${status} | ${s.wall_s} | ${s.result_count} | ${fp} |\n`;
  }
}

md += '\n## 2. Per-video full-metadata calls (top 3 per query)\n\n';
md += '| place | run | topic | query | # | video | status | wall s | uploaded | days old | dur (min) | views | followers | zh track | en track |\n|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|\n';
for (const { doc } of runs) {
  for (const q of doc.queries) {
    for (const v of q.videos) {
      if (v.status !== 'ok') {
        md += `| ${doc.place} | ${doc.run} | ${q.topic_id} | ${esc(q.query)} | ${v.rank} | ${v.id} | ERR: ${esc((v.error || '').split('\n').pop() || v.error)} | ${v.wall_s} | - | - | - | - | - | - | - |\n`;
        continue;
      }
      const age = daysBetween(doc.started_at, v.upload_date);
      md += `| ${doc.place} | ${doc.run} | ${q.topic_id} | ${esc(q.query)} | ${v.rank} | ${v.id} | ok | ${v.wall_s} | ${v.upload_date ?? '-'} | ${age ?? '-'} | ${v.duration != null ? (v.duration / 60).toFixed(1) : '-'} | ${v.view_count ?? '-'} | ${v.channel_follower_count ?? '-'} | ${v.captions.has_zh ? 'yes' : 'no'} | ${v.captions.has_en ? 'yes' : 'no'} |\n`;
    }
  }
}

md += '\n## 3. Supply: unique probed videos per topic and place, duration 8-90 min\n\n';
md += 'Counts dedupe by video id across that place\'s runs and the topic\'s queries. "probed" = videos that got the second (full-metadata) call; flat search entries carry no upload date, so only probed videos can be dated.\n\n';
md += '| topic | place | probed | meta ok | in duration band | <=7 days | <=30 days | no upload date |\n|---|---|---|---|---|---|---|---|\n';
const topicIds = [...new Set(runs.flatMap(({ doc }) => doc.queries.map((q) => q.topic_id)))];
const places = [...new Set(runs.map(({ doc }) => doc.place))].sort();
for (const topic of topicIds) {
  for (const place of places) {
    const seen = new Map(); // id -> {age, duration}
    for (const { doc } of runs.filter((r) => r.doc.place === place)) {
      for (const q of doc.queries.filter((q) => q.topic_id === topic)) {
        for (const v of q.videos) {
          if (!seen.has(v.id)) seen.set(v.id, { status: v.status, age: daysBetween(doc.started_at, v.upload_date), duration: v.duration });
        }
      }
    }
    if (seen.size === 0) continue;
    const ok = [...seen.values()].filter((v) => v.status === 'ok');
    const inBand = ok.filter((v) => v.duration != null && v.duration >= MIN_S && v.duration <= MAX_S);
    const d7 = inBand.filter((v) => v.age != null && v.age <= 7).length;
    const d30 = inBand.filter((v) => v.age != null && v.age <= 30).length;
    const noDate = inBand.filter((v) => v.age == null).length;
    md += `| ${topic} | ${place} | ${seen.size} | ${ok.length} | ${inBand.length} | ${d7} | ${d30} | ${noDate} |\n`;
  }
}

md += '\n## 4. Errors (exact text)\n\n';
const errs = [];
for (const { doc } of runs) {
  for (const q of doc.queries) {
    if (q.search.status !== 'ok') errs.push({ where: `${doc.place}/${doc.run} search "${q.query}"`, text: q.search.error });
    for (const v of q.videos) if (v.status !== 'ok') errs.push({ where: `${doc.place}/${doc.run} video ${v.id} ("${q.query}" #${v.rank})`, text: v.error });
  }
}
if (errs.length === 0) {
  md += 'None.\n';
} else {
  for (const e of errs) md += `- **${e.where}**:\n  \`\`\`\n  ${e.text}\n  \`\`\`\n`;
}

const notes = join(here, 'notes.md');
if (existsSync(notes)) md += '\n' + readFileSync(notes, 'utf8');
writeFileSync(join(here, 'REPORT.md'), md);
console.log(`REPORT.md written from ${files.length} result files: ${files.join(', ') || '(none)'}`);
